/// `analysis_YYYY-MM-DD_HH-MM.html` (UTC).
fn timestamped_report_name() -> String {
    let secs = history::now_ms() / 1000;
    let days = secs / 86400;
    let rem = secs % 86400;
    let (h, min) = (rem / 3600, (rem % 3600) / 60);
    // Howard Hinnant's civil-from-days.
    let z = days as i64 + 719_468;
    let era = z.div_euclid(146_097);
    let doe = (z - era * 146_097) as u64;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146_096) / 365;
    let y = yoe as i64 + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let mon = if mp < 10 { mp as i64 + 3 } else { mp as i64 - 9 };
    let year = if mon <= 2 { y + 1 } else { y };
    format!("analysis_{year:04}-{mon:02}-{d:02}_{h:02}-{min:02}.html")
}

/// "Jun 21, 2026 · 09:45" from a report filename.
pub fn format_report_name(filename: &str) -> String {
    const MONTHS: [&str; 12] = [
        "Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec",
    ];
    let parse = || -> Option<String> {
        let stem = filename.strip_prefix("analysis_")?.strip_suffix(".html")?;
        let (date, time) = stem.split_once('_')?;
        let mut d = date.split('-');
        let (year, mon, day) = (d.next()?, d.next()?.parse::<usize>().ok()?, d.next()?);
        let (h, m) = time.split_once('-')?;
        let day: u32 = day.parse().ok()?;
        Some(format!("{} {day}, {year} · {h}:{m}", MONTHS.get(mon.checked_sub(1)?)?))
    };
    parse().unwrap_or_else(|| filename.to_string())
}

/// Correct/refine entries whose target differs from the native language;
/// falls back to all correct/refine entries.
fn l2_entries<'a>(entries: &'a [HistoryEntry], native_lang: &str) -> Vec<&'a HistoryEntry> {
    let corrections: Vec<_> = entries
        .iter()
        .filter(|e| e.mode == "correct" || e.mode == "refine")
        .collect();
    let l2: Vec<_> = corrections
        .iter()
        .copied()
        .filter(|e| !e.target_lang.eq_ignore_ascii_case(native_lang))
        .collect();
    if l2.is_empty() { corrections } else { l2 }
}

fn determine_l2_lang(entries: &[HistoryEntry], native_lang: &str) -> String {
    let mut counts: HashMap<&str, usize> = HashMap::new();
    for e in l2_entries(entries, native_lang) {
        *counts.entry(e.target_lang.as_str()).or_default() += 1;
    }
    counts
        .into_iter()
        .max_by_key(|(_, c)| *c)
        .map(|(lang, _)| lang.to_string())
        .unwrap_or_else(|| "English".to_string())
}

fn format_samples(entries: &[HistoryEntry], native_lang: &str) -> String {
    l2_entries(entries, native_lang)
        .iter()
        .enumerate()
        .map(|(i, e)| {
            let mut text: String = e.input_text.chars().take(1500).collect();
            if e.input_text.chars().count() > 1500 {
                text.push('…');
            }
            format!(
                "[{}] mode={} | {} → {}\n{}",
                i + 1,
                e.mode,
                e.source_lang,
                e.target_lang,
                text.trim()
            )
        })
        .collect::<Vec<_>>()
        .join("\n\n---\n\n")
}

fn extract_html(content: &str) -> String {
    content
        .find("<!DOCTYPE html>")
        .or_else(|| content.find("<!doctype html>"))
        .or_else(|| content.find("<html"))
        .map(|start| content[start..].to_string())
        .unwrap_or_else(|| content.to_string())
}

/// All saved reports, newest first.
pub fn list_reports() -> Vec<ReportInfo> {
    let mut reports: Vec<_> = std::fs::read_dir(data_dir())
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| {
            let filename = entry.file_name().to_string_lossy().to_string();
            (filename.starts_with("analysis_") && filename.ends_with(".html")).then(|| ReportInfo {
                filename,
                path: entry.path(),
            })
        })
        .collect();
    reports.sort_by(|a, b| b.filename.cmp(&a.filename));
    reports
}

/// Runs the whole analysis (blocking), reporting progress through `progress`.
/// Returns the saved report path.
pub fn run(
    settings: &Settings,
    days_back: Option<u32>,
    progress: impl Fn(&str, u8),
) -> Result<PathBuf, String> {
    progress("Loading history entries…", 5);
    let history = history::load()?;
    if history.entries.is_empty() {
        return Err(
            "No history entries found. Enable history collection and use the app first."
                .to_string(),
        );
    }

    let cutoff = days_back.map(|d| history::now_ms().saturating_sub(d as u64 * 86_400_000));
    let entries: Vec<HistoryEntry> = history
        .entries
        .into_iter()
        .filter(|e| cutoff.is_none_or(|c| e.timestamp >= c))
        .collect();

    let native_lang = settings.preferred_lang.as_str();
    let l2_count = l2_entries(&entries, native_lang).len();
    if l2_count == 0 {
        return Err(format!(
            "No correction or refinement entries found in this period. Use the Correct or \
             Refine modes on writing that isn't in {native_lang}, then run analysis again."
        ));
    }

    let target_lang = determine_l2_lang(&entries, native_lang);
    let prompt = ANALYSIS_PROMPT
        .replace("{ENTRY_COUNT}", &entries.len().to_string())
        .replace("{TARGET_LANG}", &target_lang)
        .replace("{FORMATTED_SAMPLES}", &format_samples(&entries, native_lang));

    progress(
        &format!(
            "Analysing {l2_count} {target_lang} samples with {} — this may take a minute…",
            settings.model
        ),
        20,
    );
    let full_prompt = format!("<start_of_turn>user\n{prompt}\n<end_of_turn>\n<start_of_turn>model");
    let content = llm::complete(&LlmConfig::from_settings(settings), &full_prompt)
        .map_err(|e| format!("AI error: {e}"))?;

    progress("Generating HTML report…", 85);
    let html = extract_html(&llm::trim_thinking_blocks(&content));
    let path = data_dir().join(timestamped_report_name());
    std::fs::write(&path, html).map_err(|e| format!("Failed to save report: {e}"))?;
    Ok(path)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(mode: &str, target: &str, text: &str) -> HistoryEntry {
        HistoryEntry {
            id: 0,
            timestamp: 0,
            mode: mode.into(),
            input_text: text.into(),
            source_lang: "auto".into(),
            target_lang: target.into(),
        }
    }

    #[test]
    fn picks_l2_samples_and_language() {
        let entries = vec![
            entry("translate", "Tiếng Việt", "a"),
            entry("correct", "English", "b"),
            entry("refine", "English", "c"),
            entry("correct", "Tiếng Việt", "d"),
        ];
        assert_eq!(l2_entries(&entries, "Tiếng Việt").len(), 2);
        assert_eq!(determine_l2_lang(&entries, "Tiếng Việt"), "English");
    }

    #[test]
    fn long_multibyte_samples_do_not_panic() {
        let text = "ữ".repeat(2000);
        let out = format_samples(&[entry("correct", "English", &text)], "Tiếng Việt");
        assert!(out.ends_with('…'));
    }

    #[test]
    fn formats_report_names() {
        assert_eq!(
            format_report_name("analysis_2026-06-21_09-45.html"),
            "Jun 21, 2026 · 09:45"
        );
        assert_eq!(format_report_name("other.html"), "other.html");
        assert!(timestamped_report_name().starts_with("analysis_20"));
    }

    #[test]
    fn extracts_html_document() {
        assert_eq!(extract_html("```html\n<!DOCTYPE html><p>"), "<!DOCTYPE html><p>");
    }
}
