//! Language analysis: sends the learner's correction/refine history to the
//! configured model and saves the returned standalone HTML report.

use std::collections::HashMap;
use std::path::PathBuf;

use crate::history::{self, HistoryEntry};
use crate::llm::{self, LlmConfig};
use crate::settings::{Settings, data_dir};

#[derive(Clone, Debug, Default, PartialEq)]
pub enum Phase {
    #[default]
    Idle,
    Running {
        message: String,
        percent: u8,
    },
    Complete {
        report: PathBuf,
    },
    Error(String),
}

#[derive(Clone, Debug)]
pub struct ReportInfo {
    pub filename: String,
    pub path: PathBuf,
}

